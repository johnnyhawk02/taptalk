// Writes precache.js: the app shell (PRECACHE, must all download for an
// update to go ahead) and every symbol used by the starting board
// (PRECACHE_SYMBOLS, fetched best-effort so one failed picture can never block
// an update), so TapTalk works offline straight after install. Other Mulberry
// pictures are cached the first time they are shown (e.g. in the picker).
// Run after changing js/board.js or any app file:  node tools/build-precache.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { DEFAULT_PAGES } from '../js/board.js';

const shell = [
  './', 'index.html', 'manifest.webmanifest', 'css/styles.css',
  'js/app.js', 'js/board.js', 'js/photos.js', 'js/gphotos.js', 'js/config.js', 'js/migrate.js', 'js/sync.js', 'js/cropper.js', 'js/sheet.js', 'js/merge.js', 'repair.html', 'symbols/index.json',
  'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png',
];
const syms = new Set(readdirSync('symbols/custom').map((f) => 'symbols/custom/' + f));
for (const page of Object.values(DEFAULT_PAGES)) {
  for (const [, sym] of [...page.items, ...(page.icon ? [[null, page.icon]] : [])]) {
    if (sym.startsWith('m:')) syms.add('symbols/mulberry/' + encodeURIComponent(sym.slice(2)) + '.svg');
    if (sym.startsWith('a:')) syms.add('symbols/arasaac/' + encodeURIComponent(sym.slice(2)) + '.png');
  }
}
const symbols = [...syms].sort();
const files = [...shell, ...symbols];

const hash = createHash('sha256');
hash.update(readFileSync('sw.js'));
for (const f of files) if (f !== './') hash.update(readFileSync(decodeURIComponent(f)));
const version = hash.digest('hex').slice(0, 10);

const list = (a) => JSON.stringify(a, null, 0).replace(/","/g, '",\n  "');
writeFileSync('precache.js', `// Generated by tools/build-precache.mjs — do not edit.\nself.CACHE_VERSION = '${version}';\nself.PRECACHE = ${list(shell)};\nself.PRECACHE_SYMBOLS = ${list(symbols)};\n`);
console.log(`precache.js: ${shell.length} app files + ${symbols.length} pictures, version ${version}`);
