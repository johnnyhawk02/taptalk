// Writes precache.js: the app shell plus every symbol used by the starting
// board, so TapTalk works offline straight after install. Other Mulberry
// pictures are cached the first time they are shown (e.g. in the picker).
// Run after changing js/board.js or any app file:  node tools/build-precache.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { DEFAULT_PAGES } from '../js/board.js';

const shell = [
  './', 'index.html', 'manifest.webmanifest', 'css/styles.css',
  'js/app.js', 'js/board.js', 'js/photos.js', 'js/gphotos.js', 'js/config.js', 'symbols/index.json',
  'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png',
];
const syms = new Set(readdirSync('symbols/custom').map((f) => 'symbols/custom/' + f));
for (const page of Object.values(DEFAULT_PAGES)) {
  for (const [, sym] of page.items) {
    if (sym.startsWith('m:')) syms.add('symbols/mulberry/' + encodeURIComponent(sym.slice(2)) + '.svg');
  }
}
const files = [...shell, ...[...syms].sort()];

const hash = createHash('sha256');
for (const f of files) if (f !== './') hash.update(readFileSync(decodeURIComponent(f)));
const version = hash.digest('hex').slice(0, 10);

writeFileSync('precache.js', `// Generated by tools/build-precache.mjs — do not edit.\nself.CACHE_VERSION = '${version}';\nself.PRECACHE = ${JSON.stringify(files, null, 0).replace(/","/g, '",\n  "')};\n`);
console.log(`precache.js: ${files.length} files, version ${version}`);
